def curation(file):
    mafft_cline = MafftCommandline(input=file,reorder=True,genafpair=True,thread=int(cpunum))
    stdout, stderr = mafft_cline()
    align = AlignIO.read(StringIO(stdout), "fasta")
    nseq=len(align)
    for seq in range(nseq):
        align[seq].seq=Seq(str(align[seq].seq).upper())
    AlignIO.write(align,f'{file}_aln.fasta','fasta')

    if nseq<3:
        print(f"Only {len(align)} sequences, skipped curating ORF")
        return
    aln_len=align.get_alignment_length()
    print(f'Alignment length is {aln_len}')

    col_to_remove=[]
    #identify gap columns can be removed        
    i = 0
    gap_freq_to_remove=0.8
    
    while i < aln_len:
        if align[:, i].count('-') / nseq > gap_freq_to_remove:
            if i == 0:
                gap_con=[str(s.seq) for s in list(align[:,0:2])].count('--')
                print(f"{i} {gap_con}")
                if (align[:, i].count('-')-gap_con) / (nseq-gap_con) > gap_freq_to_remove:
                    col_to_remove.append(i)
            elif i+1 == aln_len:
                gap_con=[str(s.seq) for s in list(align[:,i-2:aln_len])].count('--')
                print(f"{i} {gap_con}")
                if (align[:, i-1].count('-')-gap_con) / (nseq-gap_con) > gap_freq_to_remove:
                    col_to_remove.append(i)
            elif i+2<aln_len:
                gap_con1=[str(s.seq) for s in list(align[:,i-1:i+1])].count('--')
                gap_con2=[str(s.seq) for s in list(align[:,i:i+2])].count('--')
                gap_con3=[str(s.seq) for s in list(align[:,i+1:i+3])].count('--')
                gap_ratio_i=(align[:, i].count('-')-gap_con1) / (nseq-gap_con1)
                gap_ratio_ia=(align[:, i].count('-')-gap_con2) / (nseq-gap_con2)
                gap_ratio_b=(align[:, i-1].count('-')-gap_con1) / (nseq-gap_con1)
                gap_ratio_a=(align[:, i+1].count('-')-gap_con2) / (nseq-gap_con2)
                gap_ratio_i1=(align[:, i+1].count('-')-gap_con3) / (nseq-gap_con3)
                gap_ratio_i2=(align[:, i+2].count('-')-gap_con3) / (nseq-gap_con3) 
                
                if  gap_ratio_i > gap_freq_to_remove and gap_ratio_b < 0.3:
                    if gap_ratio_ia > gap_freq_to_remove and gap_ratio_a < 0.3 and gap_ratio_i1 < gap_freq_to_remove:
                        col_to_remove.append(i)
                    elif i<aln_len-2 and gap_ratio_i1 >= gap_freq_to_remove and gap_ratio_i2 < 0.3:
                        col_to_remove.append(i)
                        col_to_remove.append(i+1)
                    else:
                        print(f"did not edit {i}")
            i+=1
        else:  #  nothing to delete, proceed
            i +=1 
    col_to_remove=sorted(col_to_remove)
    i=0
    
    print(f"Alignment columns to remove: {col_to_remove}")
    if len(col_to_remove)==0:
        align1=align
    else:
        while i < len(col_to_remove):
            if i==0:
                if col_to_remove[i]>0:
                    align1=align[:,0:col_to_remove[i]]
                    if col_to_remove[i]==aln_len-1:
                        align1=align[:,0:col_to_remove[i]-1]
                    elif len(col_to_remove)==1:
                        align1+=align[:,col_to_remove[i]+1:aln_len]
                    else:
                        align1+=align[:,col_to_remove[i]+1:col_to_remove[i+1]]
                else:
                    align1=align[:,1:col_to_remove[i+1]]
            elif i==len(col_to_remove)-1:
                if col_to_remove[i]<aln_len-1:
                    align1+=align[:,col_to_remove[i]+1:aln_len]
                #else:
                #    align1+=align[:,col_to_remove[i]+1:aln_len-1]
            else:
                align1+=align[:,col_to_remove[i]+1:col_to_remove[i+1]]           
            i+=1
        
    #remove sequence specific ORF indel
    nt_coln={}
    aln_len=align1.get_alignment_length()
    i=0
    for i in range(aln_len):
        nt_coln[i]={}
        for j in range(len(align1)):
            if align1[j,i] not in nt_coln[i]:
                nt_coln[i][align1[j,i].upper()]=1
            else:
                nt_coln[i][align1[j,i].upper()]+=1
        if not '-' in nt_coln[i]:
            nt_coln[i]['-']=0

    i=0
    total_corrected=0
    while i < nseq:
        count1=0
        seq=str(align1[i].seq)
        for match in re.finditer('\w\-\w',seq):
            count=sorted(nt_coln[match.start()+1].items(), key=lambda t: t[1],reverse=True)
            if count[0][0]!='-':
                seq=seq[:match.start()+1]+count[0][0]+seq[match.start()+2:]
                align1[i].seq=Seq(seq)
                print(f"{align1[i].id} position {match.start()+1} is curated to {count[0][0]}")
                count1 +=1
        for match in re.finditer('^\-\w',seq):
            count=sorted(nt_coln[match.start()].items(), key=lambda t: t[1],reverse=True)
            if count[0][0]!='-':
                seq=count[0][0]+seq[match.start()+1:]
                align1[i].seq=Seq(seq)
                print(f"{align1[i].id} position {match.start()} is curated to {count[0][0]}")
                count1 +=1
        for match in re.finditer('^\w\-$',seq):
            count=sorted(nt_coln[match.start()+1].items(), key=lambda t: t[1],reverse=True)
            if count[0][0] !='-':
                seq=seq[:match.start()+1]+count[0][0]
                align1[i].seq=Seq(seq)
                print(f"{align1[i].id} position {match.start()} is curated to {count[0][0]}")
                count1 +=1
        for match in re.finditer('\w\-\-\w',seq):
            count=sorted(nt_coln[match.start()+1].items(), key=lambda t: t[1],reverse=True)
            count2=sorted(nt_coln[match.start()+2].items(), key=lambda t: t[1],reverse=True)
            if count[0][0] !='-' and count2[0][0] !='-':
                seq=seq[:match.start()+1]+count[0][0]+count2[0][0]+seq[match.start()+3:]
                align1[i].seq=Seq(seq)
