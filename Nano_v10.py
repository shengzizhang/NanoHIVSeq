def bin_clusters(file1, id1):
    file_out = file1 + "_out"
    if args.vsearch is True:
        subprocess.call(f"{vsearch} --fastx_uniques {file1}  --fastaout {file_out}.nonredundant.fa --sizeout --uc {file_out}.cluster", shell=True)
        derep1 = derep(file_out + ".cluster", 0)
        subprocess.call(f"{vsearch} --sortbysize {file_out}.nonredundant.fa --output {file_out}.nonredundant1.fa", shell=True)
        subprocess.call(f"{vsearch} --cluster_smallmem {file_out}.nonredundant1.fa --threads {cpunum} --minsl 0.5 --id {id1} --usersort --maxrejects 48 --maxaccepts 3 --sizein --sizeout --uc  {file_out}.cluster --centroids {file_out}.unique.fa", shell=True)               
    else:
        subprocess.call(f"{usearch} -fastx_uniques {file1} -threads {cpunum} -fastaout {file_out}.nonredundant.fa -sizeout -uc {file_out}.cluster", shell=True)
