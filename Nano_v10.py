def fragment(name, seq):
    i = 0
    out = ''
    while i < len(seq):
        out += f"{name}\n{seq[i:i+300]}\n"
        i += 100
    return out
        
def assign_subtype(folder,fo):
    check_status=check_finish(folder)    
    if check_status==2 or args.force:
        subprocess.call(f"{blastn} -db {HIVref} -query " + args.o + f"/HMM{fo}/envs_nt_orf_unique_frag.fasta -out " + folder + "/blastn.txt -outfmt '6 qseqid sseqid pident length mismatch gaps qstart qend sstart send evalue bitscore sstrand' -gapopen 5 -gapextend 2 -penalty -1 -num_threads " + str(cpunum)  + " -reward 1 -evalue 1e-3 -max_target_seqs 1", shell=True)
        f=open(folder + "/blastn.txt", 'r') 
        subtype = {}
        for line in f:
            ll = line.strip().split('\t')
            subt = ll[1].split('.')[1]
            if not ll[0] in subtype:
                subtype[ll[0]]={}
            if not subt in subtype[ll[0]]:
                subtype[ll[0]][subt]=1
            else:
                subtype[ll[0]][subt]+=1
        with open(folder + "/subtype.txt", 'w') as f1:
            f1.write("seqID\tlength\tseed_NGS_depth\ttotal_NGSdepth\tsubtype\n")
            for seqname in sorted(subtype):
                subs = sorted(subtype[seqname], key=lambda x: subtype[seqname][x], reverse=True)
                seqname=seqname.replace('_length=','\t').replace(';rawsize=','\t').replace(';size=','\t')
                f1.write(seqname + "\t" + subs[0] + "\n")
    else:
        print(f"Skipping subtype assignment for {folder} since it was done")
def translation(seq):
    aa = [''] * 3
    for i in range(3):
        for j in range(i, len(seq), 3):
            if len(seq[j:j+3]) < 3:
                break
            if seq[j:j+3] in codon_to_aa:
                aa[i] += codon_to_aa[seq[j:j+3]]
            else:
                aa[i] += 'X'
    return aa
