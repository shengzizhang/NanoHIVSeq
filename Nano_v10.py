def write_statistics(filepath,fileformat='fasta'):
    count_r = 0
    if os.path.exists(filepath):
        if fileformat =='fa' or fileformat =='fasta':
            with open(filepath) as fs:
                for line in fs:
                    if line.startswith(">"):
                        count_r += 1
            fs.close()
            return(count_r)
        elif fileformat =='fq' or fileformat =='fastq':
            
            with open(filepath) as fs:
                for line in fs:
                        count_r += 1
            fs.close()
            return(int(count_r//4))
    else:
        print(f"{filepath} does not exist!")
        return(count_r)    
                
