def spikein_error_rate(spike_path):
    count = 0
    with open(f"{spike_path}/adapter_removed_spikein.fa") as f:
        for line in f:
            if line.startswith(">"):
                count += 1
    if count >10000:
        if args.vsearch is True:
            os.system(f"{vsearch} --fastx_subsample {spike_path}/adapter_removed_spikein.fa --sample_size 10000 --randseed 42 --fastaout {spike_path}/spikein_10000.fa;{blastn} -db {spikeinfile} -query {spike_path}/spikein_10000.fa -outfmt '6 qseqid sseqid pident length mismatch gaps qstart qend sstart send evalue bitscore sstrand' -gapopen 5 -gapextend 2 -penalty -1 -num_threads {cpunum}  -reward 1 -evalue 1e-3 -max_target_seqs 1 >{spike_path}/spikein_blastn.txt")
        else:
            os.system(f"{usearch} -fastx_subsample {spike_path}/adapter_removed_spikein.fa -sizein -sizeout -sample_size 10000 -fastaout {spike_path}/spikein_10000.fa;{blastn} -db /data2/Zizhang/Antibodyomics/nanopore/HMM/nanopore_spikein -query {spike_path}/spikein_10000.fa -outfmt '6 qseqid sseqid pident length mismatch gaps qstart qend sstart send evalue bitscore sstrand' -gapopen 5 -gapextend 2 -penalty -1 -num_threads {cpunum}  -reward 1 -evalue 1e-3 -max_target_seqs 1 >{spike_path}/spikein_blastn.txt")
    else:
        os.system(f"{blastn} -db {spikeinfile} -query {spike_path}/adapter_removed_spikein.fa -outfmt '6 qseqid sseqid pident length mismatch gaps qstart qend sstart send evalue bitscore sstrand' -gapopen 5 -gapextend 2 -penalty -1 -num_threads {cpunum}  -reward 1 -evalue 1e-3 -max_target_seqs 1 >{spike_path}/spikein_blastn.txt")
    df = pd.read_csv(f"{spike_path}/spikein_blastn.txt", sep='\t')
    df=df[df.iloc[:,2]>90]
    df.iloc[:,2]=100-df.iloc[:,2]
    df_low=[]
    df_high=[]
    j=0
    for i in df.iloc[:,0]:
        nt=re.findall(';',str(i))
        if len(nt)>2:
            df_high.append(df.iloc[j,2])
        else:
            df_low.append(df.iloc[j,2])
        j+=1
        
    plt.hist(df_low,bins=100,color = "skyblue")
    plt.hist(df_high,bins=100,alpha=0.5,color = "red")
    plt.hist(df.iloc[:,2],bins=100)
    plt.xlabel('Error %')
    plt.ylabel('Frequency')
    plt.savefig(f"{spike_path}/pikein_errorrate.png")
    plt.close()
    #print("Spikein error rate high quality mean: "+str(np.mean(df_high))+"\n")
    #print("Spikein error rate high quality std: "+str(np.std(df_high))+"\n")
    print("Spikein error rate mean: "+str(np.mean(df_low))+"\n")
    print("Spikein error rate std: "+str(np.std(df_low))+"\n")
    with open(f"{spike_path}/spikein_error.txt",'w') as f:
        f.write(f"Spikein_mean_error\tSD\n{np.mean(df_low)}\t{np.std(df_low)}\n")
    f.close()

