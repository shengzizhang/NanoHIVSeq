def HMM_to_fasta(fastafile, hmmtable,fastaout,writep='w',correction='F',attach_region='T'):    
    envs = {}
    with open(fastafile, 'r') as f1:                
        for line in f1:
            if line.startswith('>'):
                if attach_region=='F':
                    id1 = re.split("[\s\t]+",line.strip())
                else:
                    id1 = re.split("[\s\t]+",line.strip().replace(';','-'))
                
            else:
                if id1[0] in envs:
                    envs[id1[0]] += line.strip()
                else:
                    envs[id1[0]] = line.strip()
    f1.close()
    with open(fastaout, writep) as fo:
        with open(hmmtable, 'r') as f2:
            next(f2)
            next(f2)
            #next(f2)
            for line in f2:
                if line.startswith('#'):
                    break	
                l = re.split("\s+",line.strip())
                #print(l)
                #min_val = min(int(l[15]), int(l[16]))
                starthit=int(l[6])
                endhit=int(l[7])
                min_val = min(starthit, endhit)
                if abs(int(l[5]) - int(l[4])) + 1 > 1800 and abs(starthit - endhit) + 1 > 1800:
                    #print(">" + l[0] + "-" + l[6] + "-" + l[7] + "\n")
                    if ">" + l[0] in envs :
                        if starthit <endhit:
                            if 'F' in correction:
                                if starthit>1 and starthit<10 and envs[">" + l[0]].startswith('ATG'):
                                    starthit=1
                            if 'T' in attach_region:
                                fo.write(">" + l[0] + "-" + str(starthit) + "-" + str(endhit) + "\n" + envs[">" + l[0]][starthit - 1:endhit] + "\n")
                            else:
                                fo.write(">" + l[0] +  "\n" + envs[">" + l[0]][starthit - 1:endhit] + "\n")
                        else:
                            if 'F' in correction:
                                if endhit>1 and endhit<10 and envs[">" + l[0]].endswith('CAT'):
                                    endhit=1
                            dna=Seq(envs[">" + l[0]][endhit - 1:starthit])
                            seq=dna.reverse_complement()
                            #print(f"{l[0]}\n{dna}\n{seq}\n")
                            if 'T' in attach_region:
                                fo.write(">" + l[0] + "-" + str(starthit) + "-" + str(endhit) + "\n" + str(seq) + "\n") 
